/// An append-only event in the structured plan review workflow.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct PlanReviewEntry {
    pub timestamp: String,
    #[serde(flatten)]
    pub event: PlanReviewEvent,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(tag = "action", rename_all = "snake_case")]
pub enum PlanReviewEvent {
    Comment {
        id: u64,
        start_line: usize,
        end_line: usize,
        text: String,
        revision: String,
        excerpt: String,
    },
    Resolve {
        id: u64,
    },
    Reopen {
        id: u64,
    },
}

/// Current state reconstructed from append-only plan review events.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PlanReviewComment {
    pub id: u64,
    pub start_line: usize,
    pub end_line: usize,
    pub text: String,
    pub revision: String,
    pub excerpt: String,
    pub resolved: bool,
}

#[must_use]
pub fn reconstruct_plan_review(events: &[PlanReviewEntry]) -> Vec<PlanReviewComment> {
    let mut comments = Vec::new();
    for entry in events {
        match &entry.event {
            PlanReviewEvent::Comment {
                id,
                start_line,
                end_line,
                text,
                revision,
                excerpt,
            } => comments.push(PlanReviewComment {
                id: *id,
                start_line: *start_line,
                end_line: *end_line,
                text: text.clone(),
                revision: revision.clone(),
                excerpt: excerpt.clone(),
                resolved: false,
            }),
            PlanReviewEvent::Resolve { id } => {
                if let Some(comment) = comments.iter_mut().find(|comment| comment.id == *id) {
                    comment.resolved = true;
                }
            }
            PlanReviewEvent::Reopen { id } => {
                if let Some(comment) = comments.iter_mut().find(|comment| comment.id == *id) {
                    comment.resolved = false;
                }
            }
        }
    }
    comments
}

fn default_true() -> bool {
    true
}

/// Computed session statistics (not serialized to JSONL).
///
/// Aggregates metrics across all messages in a session for display purposes.
/// These values are calculated during session reading and are not stored in
/// the session file itself.
///
/// # Usage
///
/// ```rust,ignore
/// let session = SessionReader::read_file(path)?;
/// println!("Total messages: {}", session.stats.total_messages());
/// println!("Token usage: {} in, {} out",
///     session.stats.total_input_tokens,
///     session.stats.total_output_tokens);
/// println!("Total cost: ${:.4}", session.stats.total_cost);
/// ```
#[derive(Debug, Clone, Default)]
pub struct SessionStats {
    /// Count of user messages in the session.
    pub user_messages: usize,

    /// Count of assistant messages in the session.
    pub assistant_messages: usize,

    /// Count of tool call requests made by the assistant.
    pub tool_calls: usize,

    /// Count of tool result messages sent back to the assistant.
    pub tool_results: usize,

    /// Sum of all input tokens across assistant messages.
    pub total_input_tokens: u64,

    /// Sum of all output tokens across assistant messages.
    pub total_output_tokens: u64,

    /// Sum of all costs across assistant messages (in USD).
    pub total_cost: f64,
}

impl SessionStats {
    #[must_use]
    pub fn total_messages(&self) -> usize {
        self.user_messages + self.assistant_messages + self.tool_results
    }
}


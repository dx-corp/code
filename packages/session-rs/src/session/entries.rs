//! Session Entry Type Definitions
//!
//! This module defines the type system for session persistence using the JSONL format.
//! Each entry represents a distinct event in the session timeline and is serialized as
//! a single line in the session file.
//!
//! # Entry Type Hierarchy
//!
//! The [`SessionEntry`] enum is the top-level discriminated union that encompasses all
//! possible event types in a session. It uses serde's `tag` attribute to create a
//! type-discriminated JSON representation.
//!
//! ## Serde Tagged Enum Pattern
//!
//! Each entry is serialized with a `"type"` field that determines its variant:
//! ```json
//! {"type":"session","id":"abc123",...}
//! {"type":"message","timestamp":"2024-01-15T10:30:00Z",...}
//! {"type":"session_meta","title":"My Session",...}
//! ```
//!
//! The `#[serde(tag = "type", rename_all = "snake_case")]` attribute automatically:
//! - Adds a `"type"` discriminator field to each JSON object
//! - Converts variant names from `PascalCase` to `snake_case` (Session -> "session")
//! - Enables efficient deserialization by reading the type field first
//!
//! # Message Format
//!
//! Messages follow a role-based structure compatible with AI provider APIs:
//!
//! ## User Messages
//! ```json
//! {
//!   "role": "user",
//!   "content": "What is Rust?",
//!   "timestamp": 1705318200000
//! }
//! ```
//!
//! ## Assistant Messages
//! ```json
//! {
//!   "role": "assistant",
//!   "content": [
//!     {"type": "text", "text": "Rust is a systems programming language..."},
//!     {"type": "thinking", "text": "Consider explaining memory safety..."}
//!   ],
//!   "usage": {
//!     "input": 150,
//!     "output": 200,
//!     "cacheRead": 100,
//!     "cacheWrite": 50
//!   },
//!   "timestamp": 1705318201000
//! }
//! ```
//!
//! ## Tool Result Messages
//! ```json
//! {
//!   "role": "toolResult",
//!   "tool_call_id": "call_xyz",
//!   "tool_name": "read_file",
//!   "content": "File contents here...",
//!   "is_error": false,
//!   "timestamp": 1705318202000
//! }
//! ```
//!
//! # Content Block Types
//!
//! Assistant messages contain structured content blocks:
//!
//! - **Text**: Plain text responses
//! - **Thinking**: Internal reasoning (extended thinking feature)
//! - **`ToolCall`**: Function calls to external tools
//! - **Image**: Base64-encoded images
//!
//! # Metadata and Configuration
//!
//! Sessions track configuration changes over time:
//!
//! ## Session Metadata
//! User-facing metadata for organization:
//! - `title`: Display name for the session
//! - `summary`: Brief description of the conversation
//! - `tags`: Categorization labels
//! - `favorite`: Pin important sessions
//!
//! ## Configuration Changes
//! Tracked as separate entries:
//! - `ThinkingLevelChange`: Adjustments to extended thinking budget
//! - `ModelChange`: Switching between AI models mid-session
//! - `Compaction`: Context window compression events
//!
//! # Token Usage Tracking
//!
//! The [`TokenUsage`] struct tracks API consumption with cache awareness:
//! - `input`: Tokens sent to the model
//! - `output`: Tokens generated by the model
//! - `cache_read`: Tokens served from prompt cache (discounted)
//! - `cache_write`: Tokens written to cache for future use
//!
//! Cost is calculated per-token based on model pricing.
//!
//! # Serialization Details
//!
//! ## Optional Field Handling
//!
//! Fields marked with `#[serde(skip_serializing_if = "Option::is_none")]` are omitted
//! from JSON when `None`, reducing file size:
//! ```rust,ignore
//! #[derive(Serialize)]
//! struct Example {
//!     required: String,
//!     #[serde(skip_serializing_if = "Option::is_none")]
//!     optional: Option<String>,  // Omitted if None
//! }
//! ```
//!
//! ## Default Values
//!
//! Fields marked with `#[serde(default)]` use `Default::default()` when missing during
//! deserialization, enabling backward compatibility:
//! ```rust,ignore
//! #[derive(Deserialize)]
//! struct Example {
//!     #[serde(default)]
//!     new_field: bool,  // Defaults to false for old files
//! }
//! ```
//!
//! ## Field Renaming
//!
//! JavaScript-style camelCase is preserved for API compatibility:
//! ```rust,ignore
//! #[derive(Serialize)]
//! struct TokenUsage {
//!     #[serde(rename = "cacheRead")]
//!     cache_read: u64,  // Serializes as "cacheRead"
//! }
//! ```
//!
//! # Rust Type System Features
//!
//! ## Newtype Pattern for Type Safety
//!
//! String fields use owned `String` types rather than references because session data
//! must outlive the file read operation. This requires allocating owned data.
//!
//! ## Enum Variants with Data
//!
//! The `MessageContent` enum demonstrates Rust's powerful enum variants:
//! ```rust,ignore
//! pub enum MessageContent {
//!     Text(String),           // Tuple variant
//!     Blocks(Vec<ContentBlock>),  // Tuple variant with complex type
//! }
//! ```
//!
//! Serde's `#[serde(untagged)]` attribute makes this serialize as either a plain string
//! or an array, without a type discriminator:
//! ```json
//! "content": "Simple text"
//! // or
//! "content": [{"type":"text","text":"Block text"}]
//! ```
//!
//! # Statistics Aggregation
//!
//! The [`SessionStats`] struct is computed during session reading and not serialized.
//! It aggregates metrics across all message entries for efficient display:
//! ```rust,ignore
//! let stats = SessionStats {
//!     user_messages: 5,
//!     assistant_messages: 5,
//!     tool_calls: 12,
//!     total_input_tokens: 15000,
//!     total_output_tokens: 8000,
//!     total_cost: 0.15,
//! };
//! ```

use super::wire_format_generated::canonical_stop_reason;
